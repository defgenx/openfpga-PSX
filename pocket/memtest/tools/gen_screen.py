#!/usr/bin/env python3
"""Generate the static text of the result screen (fpga/core/screen_text.vh).

  tools/gen_screen.py

Writes screen_text.vh (101.6 MHz build) and screen_text_135.vh (SDRAM_135 build). 40 x 30 characters. Columns 0-15 are the label, 16-39 are three 8-character fields that
report_fmt.v overwrites with numbers. A row marked HEAD is drawn in the header colour (bit 7).
Edit ROWS here; the row to result mapping lives in report_fmt.v.
"""
from pathlib import Path

HEAD = True


def row(label, h0="", h1="", h2="", head=False):
    s = label.ljust(16)[:16] + "".join(h.rjust(7)[:7] + " " for h in (h0, h1, h2))
    assert len(s) == 40, (label, len(s))
    return s, head


def rows(mhz, psram, sram, dma):
    """psram, sram and dma are the header labels of those blocks (the 135 variant says which clock they ran at)."""
    r = [
        row("MEMTEST " + mhz + "MHZ", head=HEAD),                          # 0   state, step, runs
        row("SDRAM BYTE MASK"),                                            # 1
        row("SDRAM 16B CL3", "MB/S", "ERR", "CYCLES", HEAD),               # 2
        row("SEQ WRITE"),                                                  # 3
        row("SEQ READ"),                                                   # 4
        row("RANDOM READ"),                                                # 5
        row("MIXED RD/WR"),                                                # 6
        row("EYE W/BOOT/FLAGS"),                                           # 7   capture eye width, boot centre, flags (steps)
        row("SCAN ALONE L/W/E"),                                           # 8   late lines, worst line us, data errors (640x16 line)
        row("SCAN MIXED L/W/E"),                                           # 9
        row("MIXED UNDER SCAN", "MB/S", "ERR", "CYCLES"),                  # 10
        row("TRACK MIN/MAX/MV"),                                           # 11  lowest and highest capture centre, centre moves
        row(psram, "NS/OP", "ERR", "MB/S", HEAD),                          # 12
        row("WRITE 32B"),                                                  # 13
        row("RANDOM READ 32B"),                                            # 14
        row("WALL CLK/WALKERR"),                                           # 15  wall-clock ns, address-line walk errors, MB/s
        row("CHAINED READ"),                                               # 16
        row("RD WAIT MIN/USE", "MIN", "ERRSUM", "USED"),                   # 17
        row("SYNC BURST RD16"),                                            # 18
        row("SYNC RANDOM RD"),                                             # 19
        row(sram, "NS/OP", "ERR", "CYCLES", HEAD),                         # 20
        row("RANDOM WRITE"),                                               # 21
        row("RANDOM READ"),                                                # 22
        row("WAIT MIN RD/WR", "RD", "WR", "ERRSUM"),                       # 23
        row(dma, "MB/S", "ERR", "CYCLES", HEAD),                           # 24
        row("ASYNC"),                                                      # 25
        row("SYNC BURST"),                                                 # 26
        row("SLOT SEQ KB US"),                                           # 27  kB/s, worst request us, bad requests
        row("SLOT RND KB US"),                                           # 28
        row("180NS 100M SCAN"),                                            # 29
    ]
    assert len(r) == 30
    return r


def emit(name, rws):
    data = bytearray()
    for text, head in rws:
        for ch in text:
            c = ord(ch)
            assert 32 <= c < 127
            data.append(c | (0x80 if head else 0))
    out = ["// Generated by tools/gen_screen.py - do not edit.",
           "localparam [9599:0] SCREEN_TEXT = 9600'h" + data.hex().upper() + ";"]
    Path(__file__).resolve().parent.parent.joinpath("fpga/core", name).write_text("\n".join(out) + "\n")
    print(name + ":", len(data), "characters")


emit("screen_text.vh", rows("101.6", "PSRAM 2X16 GANG", "SRAM BYTE 256K", "DMA PSRAM>SDRAM"))
emit("screen_text_135.vh", rows("135.5", "PSRAM @135.5MHZ", "SRAM @135.5MHZ", "DMA @135.5MHZ"))
