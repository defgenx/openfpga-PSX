#!/usr/bin/env python3
"""The one SDRAM timing table (AS4C32M16SB, -7 column) and the files generated from it.

    tools/sdram_timing.py           rewrite the generated files
    tools/sdram_timing.py --check   exit 1 if a committed file differs from what the table generates

Every SDRAM timing constant used by sdram_ctl.v, sim/sdram_model.v, core_constraints.sdc and
sim/gpu_diff/bwmodel.py comes from TABLE below; docs/pocket/MEMTEST.md ("SDRAM timing table") gives
the source of each figure and says which ones are not confirmed for the Pocket's part.
"""
import json
import math
import sys
from pathlib import Path

CORE = Path(__file__).resolve().parent.parent / "fpga" / "core"

PART = "AS4C32M16SB-7"
# The speed grade is the SDC comment's (core_constraints.sdc); no Pocket chip marking or schematic
# has been checked. MEMTEST.md records this.
GRADE_SOURCE = "unconfirmed: core_constraints.sdc comment, no chip marking checked"

# Fixed by the controller design, not by the datasheet.
CL = 3            # CAS latency (mode register 0x032)
BL = 4            # burst length (mode register 0x032)
INIT_NS = 203_000.0     # power-up wait before PRECHARGE ALL: datasheet 200 us, plus margin
REFI_TARGET_NS = 6_900.0  # one AUTO REFRESH per 6.9 us, below tREFI so a burst in flight cannot push it over

# name: (ns, minimum clocks, source). The cycle count at a clock is max(min clocks, ceil(ns / tCK)).
# "B-die" = AS4C32M16SB datasheet figure; "A-die" = AS4C32M16SA Rev 2.0 (-7) figure, used where the
# B-die sheet was not read; where two sources differ the slower figure is kept.
TABLE = {
    "tCK":  (7.0,    0, "B-die: CL3 minimum cycle time, 143 MHz"),
    "tAC":  (5.4,    0, "B-die: access time from CLK, CL3, max"),
    "tOH":  (2.5,    0, "A-die: data-out hold time, min"),
    "tIS":  (1.5,    0, "A-die: input setup time, min"),
    "tIH":  (0.8,    0, "A-die: input hold time, min"),
    "tRCD": (20.0,   0, "A-die 15 ns; 20 ns kept (slower of the two)"),
    "tRP":  (20.0,   0, "A-die 15 ns; 20 ns kept (slower of the two)"),
    "tRAS": (42.0,   0, "B-die: row active time, min (A-die 45)"),
    "tRC":  (63.0,   0, "B-die: row cycle time, min (A-die 65)"),
    "tWR":  (14.0,   2, "A-die tDPL 2 CLK; 14 ns kept as well"),
    "tRRD": (15.0,   0, "A-die: ACT to ACT, different banks, min"),
    "tRFC": (63.0,   0, "auto refresh cycle = tRC (B-die)"),
    "tMRD": (0.0,    2, "A-die: mode register set cycle, 2 CLK"),
    "tREFI": (64e6 / 8192, 0, "A-die: 8192 refreshes per 64 ms"),
}

# Clocks the core and the bandwidth model use, in MHz.
CLOCKS = {"101": 101.6064, "135": 135.4752}


def cycles(name, mhz):
    """Clock cycles that cover TABLE[name] at mhz."""
    ns, min_clk, _ = TABLE[name]
    return max(min_clk, math.ceil(ns * mhz / 1000.0 - 1e-9))


def derived(mhz):
    """Every cycle count sdram_ctl takes as a parameter at this clock."""
    tck = 1000.0 / mhz
    assert tck >= TABLE["tCK"][0] - 1e-9, f"{mhz} MHz is above the part's CL{CL} limit"
    d = {k: cycles(k, mhz) for k in ("tRCD", "tRP", "tRAS", "tRC", "tWR", "tRRD", "tRFC", "tMRD")}
    d["INIT"] = math.ceil(INIT_NS / tck)
    d["REF"] = math.floor(REFI_TARGET_NS / tck)
    assert d["REF"] * tck < TABLE["tREFI"][0]
    return d


def gen_vh():
    out = ["// Generated by tools/sdram_timing.py from its timing table; do not edit.",
           f"// {PART}, speed grade {GRADE_SOURCE}.",
           "`ifndef SDRAM_TIMING_VH", "`define SDRAM_TIMING_VH",
           f"`define SDT_CL {CL}", f"`define SDT_BL {BL}"]
    for key, mhz in CLOCKS.items():
        out.append(f"// {mhz} MHz")
        for k, v in derived(mhz).items():
            out.append(f"`define SDT_{key}_{k.upper()} {v}")
    out.append("// datasheet figures in ns, for the simulation model")
    for k, (ns, _, _) in TABLE.items():
        out.append(f"`define SDT_{k.upper()}_NS {ns!r}")
    out.append("// minimum clock counts, where the datasheet gives one")
    for k, (_, min_clk, _) in TABLE.items():
        if min_clk:
            out.append(f"`define SDT_{k.upper()}_CLK {min_clk}")
    out.append("`endif")
    return "\n".join(out) + "\n"


def gen_sdc():
    out = ["# Generated by tools/sdram_timing.py from its timing table; do not edit.",
           f"# {PART}, speed grade {GRADE_SOURCE}."]
    for k in ("tAC", "tOH", "tIS", "tIH"):
        out.append(f"set SDT_{k.upper()} {TABLE[k][0]!r}")
    return "\n".join(out) + "\n"


def gen_json():
    doc = {
        "generated_by": "pocket/memtest/tools/sdram_timing.py; do not edit",
        "part": PART,
        "grade_source": GRADE_SOURCE,
        "cl": CL,
        "bl": BL,
        "refi_target_ns": REFI_TARGET_NS,
        "rule": "cycles = max(min_clk, ceil(ns * MHz / 1000))",
        "timing": {k: {"ns": ns, "min_clk": m, "source": s} for k, (ns, m, s) in TABLE.items()},
        "cycles": {str(mhz): derived(mhz) for mhz in CLOCKS.values()},
    }
    return json.dumps(doc, indent=2) + "\n"


OUTPUTS = {
    CORE / "sdram_timing.vh": gen_vh,
    CORE / "sdram_timing.sdc": gen_sdc,
    CORE / "sdram_timing.json": gen_json,
}


def main(argv):
    if argv not in ([], ["--check"]):
        sys.exit("usage: sdram_timing.py [--check]")
    stale = []
    for path, gen in OUTPUTS.items():
        text = gen()
        if argv:
            if not path.exists() or path.read_text() != text:
                stale.append(path.name)
        else:
            path.write_text(text)
    if stale:
        sys.exit(f"stale generated SDRAM timing files: {', '.join(stale)} (run tools/sdram_timing.py)")


if __name__ == "__main__":
    main(sys.argv[1:])
