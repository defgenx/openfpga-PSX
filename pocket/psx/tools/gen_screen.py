#!/usr/bin/env python3
"""Generate the static text of the shell's status screen (fpga/core/status_text.vh).

  tools/gen_screen.py

40 x 30 characters. Columns 0-15 are the label, 16-39 are three 8-character fields that status_fmt.v overwrites
with values. A row marked HEAD is drawn in the header colour (bit 7). Edit ROWS here; the row to value mapping
lives in status_fmt.v. Same format as pocket/memtest/tools/gen_screen.py.
"""
from pathlib import Path

HEAD = True


def row(label, h0="", h1="", h2="", head=False):
    s = label.ljust(16)[:16] + "".join(h.rjust(7)[:7] + " " for h in (h0, h1, h2))
    assert len(s) == 40, (label, len(s))
    return s, head


def line(text, head=False):
    s = text.ljust(40)[:40]
    return s, head


ROWS = [
    row("PSX POCKET SHELL", "", "UPTIME", "", HEAD),        # 0   uptime in seconds (slot 2)
    line("THE PLAYSTATION CORE IS NOT IN THIS"),           # 1
    line("BUILD YET: THIS SCREEN TESTS THE SHELL."),       # 2
    line(""),                                              # 3
    row("SDRAM 135.5MHZ", "INIT", "CAL", "EYE", HEAD),     # 4
    row("INIT/CAL/EYE OK"),                                # 5   init done, calibration done, eye ok
    row("PLL LOCKED"),                                     # 6
    row("EYE W/BOOT/NOW"),                                 # 7   eye width, boot centre, centre now (steps)
    row("TRACK MIN/MAX/MV"),                               # 8   lowest and highest centre, centre moves
    row("FLAGS/WINDOWS"),                                  # 9   cal_flags bits 3..0, tracking windows started
    line(""),                                              # 10
    row("DATA SLOTS", "BYTES", "SUM", "", HEAD),           # 11
    row("BIOS"),                                           # 12  bytes received, word sum
    row("BIOS IS"),                                        # 13  OPENBIOS, OWN (another 512 KB BIOS), NONE or SIZE?
    row("TRACK TABLE"),                                    # 14  bytes received, word sum
    line(""),                                              # 15
    row("INPUT", "", "", "", HEAD),                        # 16
    row("PAD 1 KEYS"),                                     # 17  cont1_key[15:0]
    row("PAD 1 STICKS"),                                   # 18  cont1_joy
    line("PRESS BUTTONS: THE KEY VALUE CHANGES."),         # 19
    line(""),                                              # 20
    line(""),                                              # 21
    row("CORE OUTPUT", "", "", "", HEAD),                  # 22  the box at columns 32-39, rows 22-29
    line("RAW PIXELS OF THE CORE   ->"),                   # 23
    line(""),                                              # 24
    line(""),                                              # 25
    line(""),                                              # 26
    line(""),                                              # 27
    line(""),                                              # 28
    line("SEE DOCS/POCKET/POCKET_TOP.MD"),                 # 29
]
assert len(ROWS) == 30


def emit(name, rws):
    data = bytearray()
    for text, head in rws:
        for ch in text:
            c = ord(ch)
            assert 32 <= c < 127
            data.append(c | (0x80 if head else 0))
    out = ["// Generated by tools/gen_screen.py - do not edit.",
           "localparam [9599:0] SCREEN_TEXT = 9600'h" + data.hex().upper() + ";"]
    Path(__file__).resolve().parent.parent.joinpath("fpga/core", name).write_text("\n".join(out) + "\n")
    print(name + ":", len(data), "characters")


emit("status_text.vh", ROWS)
