#!/usr/bin/env python3
"""Generate tb_system.vhd: the real core (psx_top_pocket_flat, first-light generics) with the shell's Verilog adapters
(vram_adapter, ram_adapter, video_fl) and the behavioural memories of models.vhd, run from the BIOS. The core's inputs get
the values core_top.v gives them. Run by sim/system/run.sh; the port list is sim/mixed/ports_t.json (tools/gen_ports)."""
import json, re
from pathlib import Path

HERE = Path(__file__).resolve().parent
P = json.load(open(HERE.parent / 'mixed' / 'ports_t.json'))


def flat(t):
    if t == 'std_logic': return 'std_logic'
    if t == 'joypad_t': return 'std_logic_vector(59 downto 0)'
    if t.startswith('integer'): return 'std_logic_vector(1 downto 0)'
    m = re.search(r'\(\s*(\d+)\s+downto\s+(\d+)\s*\)', t)
    return f'std_logic_vector({m.group(1)} downto {m.group(2)})'


def zero(t):
    return "'0'" if flat(t) == 'std_logic' else "(others => '0')"


# core inputs that are not 0 (the rest of core_top.v's constants are 0); the memory and pad ports are driven below
ONE = {'syncVideoOut', 'SPUSDRAM', 'REVERBOFF', 'videoout_on', 'SPUon'}
DRIVEN = {'clk1x', 'clk2x', 'clk3x', 'clkvid', 'reset', 'ram_dataRead32', 'ram_done', 'ram_dmafifo_read', 'cache_wr',
          'cache_data', 'cache_addr', 'dma_wr', 'dma_reqprocessed', 'dma_data', 'ddr3_BUSY', 'ddr3_DOUT', 'ddr3_DOUT_READY',
          'joypad1', 'joypad2', 'joypad3', 'joypad4', 'spuram_dataRead', 'spuram_done'}

L = []
a = L.append
a("""-- System simulation of the first-light build: the real core (psx_top_pocket_flat: SPU "pocket" (RAM through spu_adapter and psx_sdram_arb into the SDRAM model), CD-ROM "pocket" with no disc, no MDEC), the shell's
-- vram_adapter, ram_adapter and video_fl, and behavioural PSRAM/SDRAM request ports with the BIOS preloaded. Writes every
-- frame the APF would get as out/frame_<n>.ppm and reports the bus activity. Generated by gen_tb.py; run.sh runs it.
-- docs/pocket/POCKET_TOP.md, "First light".
library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;

entity tb_system is
   generic (BIOS_FILE : string := "psxbios.bin"; RUN_MS : natural := 100);
end entity;

architecture sim of tb_system is
   constant T : time := 1230229 fs;  -- 1 / 812.8512 MHz: every clock is a whole number of VCO periods
   signal clk1x, clk2x, clk3x, clk_sys, clk_vid : std_logic := '0';
   signal reset, rst_mem : std_logic := '1';
""")
for n, d, t in P:
    if n in ('clk1x', 'clk2x', 'clk3x', 'clkvid', 'reset'): continue
    a(f"   signal c_{n} : {flat(t)};")
a("""   signal req_valid, req_ready, req_we, rd_valid, init_done : std_logic;
   signal req_addr : std_logic_vector(24 downto 0);
   signal req_wdata, rd_data : std_logic_vector(63 downto 0);
   signal req_be : std_logic_vector(7 downto 0);
   signal req_tag, rd_tag : std_logic;
   signal a_valid, a_ready, a_we, a_rvalid, b_valid, b_ready, b_we, b_rvalid : std_logic;
   signal a_addr, b_addr : std_logic_vector(24 downto 0);
   signal a_wdata, b_wdata : std_logic_vector(63 downto 0);
   signal a_be, b_be : std_logic_vector(7 downto 0);
   signal pc_valid, pc_ready, pc_we, pc_cfg, pr_valid, pr_done, ld_ready : std_logic;
   signal pc_addr : std_logic_vector(22 downto 0);
   signal pc_len : std_logic_vector(4 downto 0);
   signal pc_wdata, pr_data : std_logic_vector(31 downto 0);
   signal pc_be : std_logic_vector(3 downto 0);
   signal dbg_reads, dbg_writes, dbg_req, dbg_fill, dbg_dmaw : std_logic_vector(15 downto 0);
   signal fl_rgb : std_logic_vector(23 downto 0);
   signal fl_de, fl_hs, fl_vs : std_logic;
   signal frames : natural := 0;
   signal spu_rd, spu_wr, snd_peak : natural := 0;

   component vram_adapter is
      port (
         clk2x, clk_sys : in std_logic;
         ddr3_RD, ddr3_WE : in std_logic;
         ddr3_ADDR : in std_logic_vector(27 downto 0);
         ddr3_DIN : in std_logic_vector(63 downto 0);
         ddr3_BE, ddr3_BURSTCNT : in std_logic_vector(7 downto 0);
         ddr3_BUSY : out std_logic;
         ddr3_DOUT : out std_logic_vector(63 downto 0);
         ddr3_DOUT_READY : out std_logic;
         init_done : in std_logic;
         req_valid : out std_logic;
         req_ready : in std_logic;
         req_we : out std_logic;
         req_addr : out std_logic_vector(24 downto 0);
         req_wdata : out std_logic_vector(63 downto 0);
         req_be : out std_logic_vector(7 downto 0);
         rd_valid : in std_logic;
         rd_data : in std_logic_vector(63 downto 0);
         dbg_reads, dbg_writes : out std_logic_vector(15 downto 0));
   end component;

   component spu_adapter is
      port (
         clk1x, clk_sys : in std_logic;
         ena, rnw : in std_logic;
         adr : in std_logic_vector(18 downto 0);
         dataWrite : in std_logic_vector(31 downto 0);
         dataRead : out std_logic_vector(31 downto 0);
         done : out std_logic;
         req_valid : out std_logic;
         req_ready : in std_logic;
         req_we : out std_logic;
         req_addr : out std_logic_vector(24 downto 0);
         req_wdata : out std_logic_vector(63 downto 0);
         req_be : out std_logic_vector(7 downto 0);
         rd_valid : in std_logic;
         rd_data : in std_logic_vector(63 downto 0));
   end component;

   component psx_sdram_arb is
      port (
         a_valid : in std_logic; a_ready : out std_logic; a_we : in std_logic;
         a_addr : in std_logic_vector(24 downto 0); a_wdata : in std_logic_vector(63 downto 0); a_be : in std_logic_vector(7 downto 0);
         b_valid : in std_logic; b_ready : out std_logic; b_we : in std_logic;
         b_addr : in std_logic_vector(24 downto 0); b_wdata : in std_logic_vector(63 downto 0); b_be : in std_logic_vector(7 downto 0);
         c_valid : out std_logic; c_ready : in std_logic; c_we : out std_logic;
         c_addr : out std_logic_vector(24 downto 0); c_wdata : out std_logic_vector(63 downto 0); c_be : out std_logic_vector(7 downto 0);
         c_tag : out std_logic; c_rvalid : in std_logic; c_rtag : in std_logic; a_rvalid : out std_logic; b_rvalid : out std_logic);
   end component;

   component ram_adapter is
      port (
         rst, clk1x, clk3x, clk_sys : in std_logic;
         ram_ena, ram_rnw : in std_logic;
         ram_Adr : in std_logic_vector(24 downto 0);
         ram_dataWrite : in std_logic_vector(31 downto 0);
         ram_be : in std_logic_vector(3 downto 0);
         ram_dma, ram_cache : in std_logic;
         ram_cntDMA : in std_logic_vector(1 downto 0);
         ram_done : out std_logic;
         ram_dataRead32 : out std_logic_vector(31 downto 0);
         dma_wr, dma_reqprocessed : out std_logic;
         dma_data : out std_logic_vector(31 downto 0);
         cache_wr : out std_logic_vector(3 downto 0);
         cache_data : out std_logic_vector(31 downto 0);
         cache_addr : out std_logic_vector(7 downto 0);
         ram_dmafifo_empty : in std_logic;
         ram_dmafifo_adr : in std_logic_vector(22 downto 0);
         ram_dmafifo_data : in std_logic_vector(31 downto 0);
         ram_dmafifo_read : out std_logic;
         cmd_valid : out std_logic;
         cmd_ready : in std_logic;
         cmd_we, cmd_cfg : out std_logic;
         cmd_addr : out std_logic_vector(22 downto 0);
         cmd_len : out std_logic_vector(4 downto 0);
         cmd_wdata : out std_logic_vector(31 downto 0);
         cmd_be : out std_logic_vector(3 downto 0);
         rd_valid : in std_logic;
         rd_data : in std_logic_vector(31 downto 0);
         done : in std_logic;
         ld_valid : in std_logic;
         ld_ready : out std_logic;
         ld_addr : in std_logic_vector(22 downto 0);
         ld_data : in std_logic_vector(31 downto 0);
         dbg_req, dbg_fill, dbg_dmaw : out std_logic_vector(15 downto 0));
   end component;

   component video_fl is
      port (
         clk : in std_logic;
         r, g, b : in std_logic_vector(7 downto 0);
         hblank, vblank, hsync : in std_logic;
         rgb : out std_logic_vector(23 downto 0);
         de, hs, vs : out std_logic);
   end component;
begin
   clk_sys <= not clk_sys after 3 * T;
   clk3x   <= not clk3x after 4 * T;
   clk2x   <= not clk2x after 6 * T;
   clk1x   <= not clk1x after 12 * T;
   clk_vid <= not clk_vid after 60 * T;
""")
for n, d, t in P:
    if d != 'in' or n in DRIVEN: continue
    a(f"   c_{n} <= {chr(39) + '1' + chr(39) if n in ONE else zero(t)};")
a("""   -- pad 1: a digital pad with nothing pressed; the other ports unplugged. Sticks at 0x80: the gun range check in the top
   -- aborts nvc at time 0 with 0
   c_joypad1 <= "11" & "0000000000" & x"0000" & x"80808080";
   c_joypad2 <= "00" & "0000000000" & x"0000" & x"80808080";
   c_joypad3 <= "00" & "0000000000" & x"0000" & x"80808080";
   c_joypad4 <= "00" & "0000000000" & x"0000" & x"80808080";

   core : entity work.psx_top_pocket_flat
      generic map (NO_MDEC => 1, G_SPU_IMPL => "pocket", G_CD_IMPL => "pocket", G_CPU_IMPL => "pocket", G_DMA_IMPL => "pocket")
      port map (
         clk1x => clk1x, clk2x => clk2x, clk3x => clk3x, clkvid => clk2x, reset => reset,""")
pm = [f"         {n} => c_{n}" for n, d, t in P if n not in ('clk1x', 'clk2x', 'clk3x', 'clkvid', 'reset')]
a(",\n".join(pm) + ");")
a("""
   vad : vram_adapter port map (
      clk2x => clk2x, clk_sys => clk_sys,
      ddr3_RD => c_ddr3_RD, ddr3_WE => c_ddr3_WE, ddr3_ADDR => c_ddr3_ADDR, ddr3_DIN => c_ddr3_DIN, ddr3_BE => c_ddr3_BE,
      ddr3_BURSTCNT => c_ddr3_BURSTCNT, ddr3_BUSY => c_ddr3_BUSY, ddr3_DOUT => c_ddr3_DOUT, ddr3_DOUT_READY => c_ddr3_DOUT_READY,
      init_done => init_done, req_valid => a_valid, req_ready => a_ready, req_we => a_we, req_addr => a_addr,
      req_wdata => a_wdata, req_be => a_be, rd_valid => a_rvalid, rd_data => rd_data,
      dbg_reads => dbg_reads, dbg_writes => dbg_writes);

   sad : spu_adapter port map (
      clk1x => clk1x, clk_sys => clk_sys, ena => c_spuram_ena, rnw => c_spuram_rnw, adr => c_spuram_Adr,
      dataWrite => c_spuram_dataWrite, dataRead => c_spuram_dataRead, done => c_spuram_done,
      req_valid => b_valid, req_ready => b_ready, req_we => b_we, req_addr => b_addr, req_wdata => b_wdata, req_be => b_be,
      rd_valid => b_rvalid, rd_data => rd_data);

   sarb : psx_sdram_arb port map (
      a_valid => a_valid, a_ready => a_ready, a_we => a_we, a_addr => a_addr, a_wdata => a_wdata, a_be => a_be,
      b_valid => b_valid, b_ready => b_ready, b_we => b_we, b_addr => b_addr, b_wdata => b_wdata, b_be => b_be,
      c_valid => req_valid, c_ready => req_ready, c_we => req_we, c_addr => req_addr, c_wdata => req_wdata, c_be => req_be,
      c_tag => req_tag, c_rvalid => rd_valid, c_rtag => rd_tag, a_rvalid => a_rvalid, b_rvalid => b_rvalid);

   sdram : entity work.sdram_beh port map (
      clk => clk_sys, init_done => init_done, req_valid => req_valid, req_ready => req_ready, req_we => req_we,
      req_addr => req_addr, req_wdata => req_wdata, req_be => req_be, req_tag => req_tag, rd_valid => rd_valid, rd_data => rd_data,
      rd_tag => rd_tag);

   rad : ram_adapter port map (
      rst => rst_mem, clk1x => clk1x, clk3x => clk3x, clk_sys => clk_sys,
      ram_ena => c_ram_ena, ram_rnw => c_ram_rnw, ram_Adr => c_ram_Adr, ram_dataWrite => c_ram_dataWrite, ram_be => c_ram_be,
      ram_dma => c_ram_dma, ram_cache => c_ram_cache, ram_cntDMA => c_ram_cntDMA,
      ram_done => c_ram_done, ram_dataRead32 => c_ram_dataRead32,
      dma_wr => c_dma_wr, dma_reqprocessed => c_dma_reqprocessed, dma_data => c_dma_data,
      cache_wr => c_cache_wr, cache_data => c_cache_data, cache_addr => c_cache_addr,
      ram_dmafifo_empty => c_ram_dmafifo_empty, ram_dmafifo_adr => c_ram_dmafifo_adr, ram_dmafifo_data => c_ram_dmafifo_data,
      ram_dmafifo_read => c_ram_dmafifo_read,
      cmd_valid => pc_valid, cmd_ready => pc_ready, cmd_we => pc_we, cmd_cfg => pc_cfg, cmd_addr => pc_addr, cmd_len => pc_len,
      cmd_wdata => pc_wdata, cmd_be => pc_be, rd_valid => pr_valid, rd_data => pr_data, done => pr_done,
      ld_valid => '0', ld_ready => ld_ready, ld_addr => (others => '0'), ld_data => (others => '0'),
      dbg_req => dbg_req, dbg_fill => dbg_fill, dbg_dmaw => dbg_dmaw);

   psram : entity work.psram_beh generic map (BIOS_FILE => BIOS_FILE) port map (
      clk => clk_sys, cmd_valid => pc_valid, cmd_ready => pc_ready, cmd_we => pc_we, cmd_addr => pc_addr, cmd_len => pc_len,
      cmd_wdata => pc_wdata, cmd_be => pc_be, rd_valid => pr_valid, rd_data => pr_data, done => pr_done);

   vfl : video_fl port map (
      clk => clk_vid, r => c_video_r, g => c_video_g, b => c_video_b, hblank => c_hblank, vblank => c_vblank, hsync => c_hsync,
      rgb => fl_rgb, de => fl_de, hs => fl_hs, vs => fl_vs);

   grab : entity work.frame_grab generic map (PREFIX => "frame_") port map (
      clk => clk_vid, rgb => fl_rgb, de => fl_de, hs => fl_hs, vs => fl_vs, frames => frames);

   -- the memory path comes out of reset first, the core once the SDRAM is up (the BIOS is preloaded)
   process
   begin
      wait for 2 us;
      rst_mem <= '0';
      if init_done /= '1' then wait until init_done = '1'; end if;
      wait for 2 us;
      reset <= '0';
      report "core released";
      wait;
   end process;

   -- trace of the main RAM bus: the first 600 requests and every 4096th after, with the data each one returned
   process (clk1x)
      use std.textio.all;
      file tf : text open write_mode is "ram_trace.txt";
      variable l : line;
      variable n : natural := 0;
      variable pend : boolean := false;
      variable a : std_logic_vector(24 downto 0);
      variable kind : string(1 to 2);
      function hex(v : std_logic_vector) return string is
         constant d : string(1 to 16) := "0123456789ABCDEF";
         variable r : string(1 to (v'length + 3) / 4);
         variable x : unsigned(r'length * 4 - 1 downto 0) := resize(unsigned(v), r'length * 4);
      begin
         for i in r'range loop r(i) := d(to_integer(x(x'high - 4 * (i - 1) downto x'high - 4 * (i - 1) - 3)) + 1); end loop;
         return r;
      end function;
   begin
      if rising_edge(clk1x) then
         if c_ram_ena = '1' then
            n := n + 1; a := c_ram_Adr;
            if c_ram_dma = '1' then kind := "DM"; elsif c_ram_cache = '1' then kind := "FI";
            elsif c_ram_rnw = '1' then kind := "RD"; else kind := "WR"; end if;
            pend := (n <= 600 or n mod 4096 = 0);
            if pend and kind = "WR" then
               write(l, integer'image(n) & " " & time'image(now) & " WR " & hex(a) & " " & hex(c_ram_dataWrite) & " be " & hex(c_ram_be));
               writeline(tf, l); pend := false;
            end if;
         end if;
         if c_ram_done = '1' and pend then
            write(l, integer'image(n) & " " & time'image(now) & " " & kind & " " & hex(a) & " -> " & hex(c_ram_dataRead32));
            writeline(tf, l); pend := false;
         end if;
      end if;
   end process;

   -- SPU RAM accesses and the largest sound_out magnitude seen
   process (clk1x)
   begin
      if rising_edge(clk1x) then
         if c_spuram_ena = '1' then
            if c_spuram_rnw = '1' then spu_rd <= spu_rd + 1; else spu_wr <= spu_wr + 1; end if;
         end if;
         if abs(to_integer(signed(c_sound_out_left))) > snd_peak then snd_peak <= abs(to_integer(signed(c_sound_out_left))); end if;
         if abs(to_integer(signed(c_sound_out_right))) > snd_peak then snd_peak <= abs(to_integer(signed(c_sound_out_right))); end if;
      end if;
   end process;

   process
      variable n_ms : natural := 0;
   begin
      loop
         wait for 1 ms;
         n_ms := n_ms + 1;
         report integer'image(n_ms) & " ms: RAM requests " & integer'image(to_integer(unsigned(dbg_req))) &
                " fills " & integer'image(to_integer(unsigned(dbg_fill))) &
                " DMA writes " & integer'image(to_integer(unsigned(dbg_dmaw))) &
                ", VRAM reads " & integer'image(to_integer(unsigned(dbg_reads))) &
                " writes " & integer'image(to_integer(unsigned(dbg_writes))) &
                ", frames " & integer'image(frames) &
                ", SPU RAM reads " & integer'image(spu_rd) & " writes " & integer'image(spu_wr) & ", sound peak " & integer'image(snd_peak);
         if n_ms = RUN_MS then
            report "FINISH" severity note;
            std.env.finish;
         end if;
      end loop;
   end process;
end architecture;""")
(HERE / 'tb_system.vhd').write_text("\n".join(L) + "\n")
print("tb_system.vhd written")
