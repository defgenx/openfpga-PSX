#!/usr/bin/env python3
"""Generate a smoke testbench for an rtl/ entity: inputs tied to zero, clocks running, reset pulsed, no checks
beyond the simulator's own (assertions, runtime errors).

usage: mksmoke.py ENTITY SRC.vhd > tb_smoke_ENTITY.vhd
       Reads the entity's ports from SRC.vhd. Clock ports (clk1x clk2x clk3x) get 30/15/10 ns clocks in phase;
       clk2xIndex/clk3xIndex follow clk1x; reset is high for 8 clk1x cycles; ce is high. Other inputs are 0
       (every std_logic of a joypad_t is 0). The generated bench takes G_CYCLES (clk1x cycles to run).
"""
import re
import sys

CLOCKS = {"clk1x": "30 ns", "clk2x": "15 ns", "clk3x": "10 ns"}
INDEX = {"clk2xIndex", "clk3xIndex"}
JOYPAD_ZERO = ("(" + ", ".join("%s => '0'" % n for n in (
    "PadPortEnable PadPortDigital PadPortAnalog PadPortMouse PadPortGunCon PadPortNeGcon PadPortJustif PadPortDS PadPortStick "
    "PadPortPopn WheelMap ToggleDS KeyTriangle KeyCircle KeyCross KeySquare KeySelect KeyStart KeyRight KeyLeft KeyUp "
    "KeyDown KeyR1 KeyR2 KeyR3 KeyL1 KeyL2 KeyL3".split())) +
    ", " + ", ".join("%s => (others => '0')" % n for n in "Analog1X Analog1Y Analog2X Analog2Y".split()) + ")")


def split_top(s, sep):
    out, depth, cur = [], 0, ""
    for ch in s:
        depth += ch == "("
        depth -= ch == ")"
        if ch == sep and depth == 0:
            out.append(cur)
            cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur)
    return out


def parse(ent, src):
    text = open(src, errors="replace").read().replace("\r", "")
    text = re.sub(r"--[^\n]*", "", text)
    m = re.search(r"\bentity\s+%s\s+is\b(.*?)\bend\b" % ent, text, re.S | re.I)
    if not m:
        sys.exit("mksmoke: entity %s not found in %s" % (ent, src))
    body = m.group(1)
    if re.search(r"\bgeneric\s*\(", body, re.I):
        sys.exit("mksmoke: %s has generics; extend the generator" % ent)
    pm = re.search(r"\bport\s*\((.*)\)\s*;?\s*$", body.strip(), re.S | re.I)
    ports = []
    for decl in split_top(pm.group(1), ";"):
        decl = " ".join(decl.split())
        dm = re.match(r"([\w\s,]+?)\s*:\s*(in|out|buffer|inout)\s+(.*?)(?:\s*:=\s*.*)?$", decl, re.I)
        if not dm:
            sys.exit("mksmoke: cannot parse port '%s'" % decl)
        for n in dm.group(1).split(","):
            ports.append((n.strip(), dm.group(2).lower(), dm.group(3).strip()))
    uses = re.findall(r"^\s*use\s+work\.\w+\.all\s*;", re.sub(r"--[^\n]*", "", open(src, errors="replace").read()), re.M | re.I)
    return ports, [u.strip() for u in uses]


def init_value(typ):
    t = typ.lower()
    if t == "std_logic":
        return "'0'"
    if re.match(r"(std_logic_vector|unsigned|signed)\s*\(", t):
        return "(others => '0')"
    if t == "joypad_t":
        return JOYPAD_ZERO
    sys.exit("mksmoke: no tie-off for input type '%s'" % typ)


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    ent, src = sys.argv[1:]
    ports, uses = parse(ent, src)
    L = ["-- generated by mksmoke.py from %s" % src.split("/")[-1],
         "library ieee;", "use ieee.std_logic_1164.all;", "use ieee.numeric_std.all;", "use std.env.all;"]
    L += uses
    L += ["", "entity tb_smoke_%s is" % ent, "   generic (G_CYCLES : natural := 2000);", "end entity;", "",
          "architecture sim of tb_smoke_%s is" % ent]
    for n, mode, typ in ports:
        if mode == "in" and (n in CLOCKS or n in INDEX):
            L.append("   signal %s : %s := '0';" % (n, typ))
        elif mode == "in":
            L.append("   signal %s : %s := %s;" % (n, typ, "'1'" if n == "reset" else init_value(typ)))
        else:
            L.append("   signal %s : %s;" % (n, typ))
    L += ["   signal cycles : natural := 0;", "begin",
          "   dut : entity work.%s port map (" % ent,
          ",\n".join("      %s => %s" % (n, n) for n, _, _ in ports), "   );", ""]
    for n, _, _ in ports:
        if n in CLOCKS:
            L.append("   %s <= not %s after %s / 2;" % (n, n, CLOCKS[n]))
    for n, _, _ in ports:
        if n in INDEX:
            L.append("   %s <= clk1x;" % n)
    L += ["", "   process (clk1x)", "   begin",
          "      if rising_edge(clk1x) then", "         cycles <= cycles + 1;"]
    if any(n == "reset" and m == "in" for n, m, _ in ports):
        L.append("         if cycles = 8 then reset <= '0'; end if;")
    if any(n == "ce" and m == "in" for n, m, _ in ports):
        L.append("         ce <= '1';")
    L += ["         if cycles = G_CYCLES then",
          "            report \"SMOKE %s PASS cycles=\" & integer'image(cycles);" % ent,
          "            stop(0);", "         end if;", "      end if;", "   end process;", "end architecture;"]
    print("\n".join(L))


if __name__ == "__main__":
    main()
